"""Fills a public mod's install folder (<project>/<Mod>/) with everything a player needs:

    <Mod>.pak          the freshly built pak (from build_pak.py)
    INSTALL.md         hand-written install steps (Script Extender stays a link; not bundled)
    Handbook.html      the player version of the docs site, generated by BuildAdvisor/docs_site/build_player_handbook.py
    Page/              Loot Advisor only: the shippable Sets page (PAGE_SOURCES)
    Media/             mod-page banner, thumbnail, logo marks and in-game screenshots (MEDIA)

build_pak.py calls release() after every build. Run it alone to refresh the folders without building:
    python tools/release_files.py                         # both mods, pak taken from the install folder / dist
    python tools/release_files.py LootAdvisor --media     # also re-make Media/ from MEDIA (needs Pillow)
    python tools/release_files.py --out C:/scratch        # write <out>/<Mod>/ instead of the repo install folders
Media/ is only (re)made with --media or when it does not exist yet, so ordinary builds do not touch it.
Finally every file in the folder must be named in INSTALL.md (a warning lists the ones that are not).
"""
