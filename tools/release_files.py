def install_dir(mod, out=None):
    return os.path.join(out, mod) if out else os.path.join(DESKTOP, PROJECT[mod], mod)


def copy_page(mod, dst_dir):
    written = []
    for rel in PAGE_SOURCES.get(mod, []):
        src = os.path.join(DESKTOP, rel)
        if not os.path.isdir(src):
            print("  WARNING: page source missing: %s" % src)
            continue
        page_dir = os.path.join(dst_dir, "Page")
        os.makedirs(page_dir, exist_ok=True)
        for name in sorted(os.listdir(src)):
            if os.path.isfile(os.path.join(src, name)):
                shutil.copyfile(os.path.join(src, name), os.path.join(page_dir, name))
                written.append(os.path.join(page_dir, name))
    return written


def make_handbook(mod, dst_dir, out=None):
    """Run the handbook generator; on a failed leak check the old Handbook.html stays."""
    if not os.path.isfile(HANDBOOK):
        print("  WARNING: handbook generator missing: %s" % HANDBOOK)
        return []
    r = subprocess.run([sys.executable, HANDBOOK, "--mod", mod, "--out", os.path.join(dst_dir, "Handbook.html"),
                        "--media", os.path.join(install_dir("LootAdvisor", out), "Media")],
                       capture_output=True, text=True)
    sys.stdout.write("".join("  " + ln + "\n" for ln in r.stdout.splitlines()))
    if r.returncode:
        sys.stdout.write(r.stderr)
        print("  WARNING: Handbook.html for %s NOT updated (generator exit %d)" % (mod, r.returncode))
        return []
    return [os.path.join(dst_dir, "Handbook.html")]


def make_media(mod, dst_dir):
    from PIL import Image   # only needed here; the pak build itself has no dependencies
    media = os.path.join(dst_dir, "Media")
    os.makedirs(media, exist_ok=True)
    keep = {name for _, name, _ in MEDIA.get(mod, [])}
    for name in os.listdir(media):          # drop shots that were swapped out of MEDIA
        if name not in keep:
            os.remove(os.path.join(media, name))
    written = []
    for rel, name, edit in MEDIA.get(mod, []):
        src, dst = os.path.join(DESKTOP, rel), os.path.join(media, name)
        if not os.path.isfile(src):
            print("  WARNING: media source missing: %s" % src)
            continue
        if edit is None:
            shutil.copyfile(src, dst)
        else:
            im = Image.open(src).convert("RGB")
            if isinstance(edit, dict):
                for box in edit.get("cover", []):
                    # paint over with the colour just left of the box (the window background)
                    x0, y0, x1, y1 = box
                    sample = im.crop((max(0, x0 - 6), y0, x0, y1)).resize((1, 1), Image.Resampling.BOX).getpixel((0, 0))
                    im.paste(sample, box)
                if edit.get("crop"):
                    im = im.crop(edit["crop"])
            im.save(dst, quality=85, optimize=True)
        written.append(dst)
    return written


def check_install_md(dst_dir):
    """Every file in the folder must be named in INSTALL.md."""
    md = os.path.join(dst_dir, "INSTALL.md")
    if not os.path.isfile(md):
        print("  WARNING: no INSTALL.md in %s" % dst_dir)
        return False
    text = open(md, encoding="utf-8").read()
    missing = []
    for base, _, files in os.walk(dst_dir):
        for f in files:
            if f != "INSTALL.md" and f not in text:
                missing.append(os.path.relpath(os.path.join(base, f), dst_dir))
    if missing:
        print("  WARNING: INSTALL.md does not mention: %s" % ", ".join(sorted(missing)))
    return not missing


def folder_size(d):
    return sum(os.path.getsize(os.path.join(b, f)) for b, _, fs in os.walk(d) for f in fs)


def release(mod, pak, out=None, media=False):
    """Copy the pak and refresh Page/, Handbook.html (and Media/) of a public mod; returns the folder, or None."""
    if mod not in RELEASE:
        return None
    dst_dir = install_dir(mod, out)
    os.makedirs(dst_dir, exist_ok=True)
    dst_pak = os.path.join(dst_dir, mod + ".pak")
    if pak and os.path.abspath(pak) != os.path.abspath(dst_pak):
        shutil.copyfile(pak, dst_pak)
    if out:   # a scratch folder gets the hand-written INSTALL.md too
        src_md = os.path.join(install_dir(mod), "INSTALL.md")
        if os.path.isfile(src_md):
            shutil.copyfile(src_md, os.path.join(dst_dir, "INSTALL.md"))
    copy_page(mod, dst_dir)
    if media or not os.path.isdir(os.path.join(dst_dir, "Media")):
        try:
            make_media(mod, dst_dir)
        except ImportError:
            print("  WARNING: Pillow missing, Media/ not made (pip install pillow)")
    make_handbook(mod, dst_dir, out)   # after Media/: the handbook embeds one of its screenshots
    check_install_md(dst_dir)
    print("  install folder %s: %.1f MB" % (dst_dir, folder_size(dst_dir) / 1e6))
    return dst_dir


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("mods", nargs="*", default=list(RELEASE))
    ap.add_argument("--out", help="write <out>/<Mod>/ instead of the repo install folders")
    ap.add_argument("--media", action="store_true", help="re-make Media/ from MEDIA")
    a = ap.parse_args()
    for m in a.mods:
        pak = os.path.join(install_dir(m), m + ".pak")
        if not os.path.isfile(pak):
            pak = os.path.join(ROOT, "dist", m + ".pak")
        print("%s:" % m)
        release(m, pak if os.path.isfile(pak) else None, a.out, a.media)
